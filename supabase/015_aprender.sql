-- NODOS Aprender · Carrera (Empresas 015 = Finanzas 029, idénticas)
-- Idempotente: se puede correr más de una vez sin cambiar nada.
-- Todo es ficticio (montos del juego). El estado de la carrera vive en un JSON
-- versionado (`datos.version`) para poder cambiar reglas sin migrar datos.
-- No borra nada: practica_partidas y practica_contenido quedan como histórico.

-- 1. Carreras -----------------------------------------------------------------
create table if not exists public.aprender_carreras (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  numero integer not null default 1,
  semilla bigint not null,
  estado text not null default 'activa',
  etapa text not null default 'empleado',
  mes integer not null default 1,
  indice_salud integer not null default 0,
  datos jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  cerrada_en timestamptz,
  constraint aprender_carreras_estado check (estado in ('activa', 'quebrada', 'libre', 'abandonada')),
  constraint aprender_carreras_etapa check (etapa in ('empleado', 'ahorrista', 'inversor', 'emprendedor', 'libre')),
  constraint aprender_carreras_numeros check (numero >= 1 and mes >= 1 and mes <= 1200 and indice_salud between 0 and 100 and semilla >= 0),
  constraint aprender_carreras_tamano check (pg_column_size(datos) < 200000)
);
comment on table public.aprender_carreras is 'NODOS · Aprender: carreras del juego (una activa por cuenta).';
-- Una sola carrera activa por cuenta.
create unique index if not exists aprender_carreras_una_activa on public.aprender_carreras (user_id) where estado = 'activa';
create index if not exists aprender_carreras_usuario_idx on public.aprender_carreras (user_id, created_at desc);
alter table public.aprender_carreras enable row level security;
drop policy if exists "aprender_carreras: dueño" on public.aprender_carreras;
create policy "aprender_carreras: dueño" on public.aprender_carreras
  for all using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "aprender_carreras: admin lee" on public.aprender_carreras;
create policy "aprender_carreras: admin lee" on public.aprender_carreras
  for select using (public.is_admin());
drop trigger if exists aprender_carreras_touch on public.aprender_carreras;
create trigger aprender_carreras_touch before update on public.aprender_carreras
  for each row execute function public.touch_updated_at();
revoke all on public.aprender_carreras from anon;
grant select, insert, update, delete on public.aprender_carreras to authenticated;

-- 2. Turnos (un resumen por mes cerrado: historial y, en V2, ranking) ---------
-- Guarda las decisiones del mes: con la semilla, el motor puede rehacer la
-- carrera y comprobar el resultado (base para un ranking sin trampas).
create table if not exists public.aprender_turnos (
  id bigint generated by default as identity primary key,
  carrera_id uuid not null references public.aprender_carreras(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  mes integer not null,
  indice_salud integer not null default 0,
  patrimonio bigint not null default 0,
  resumen jsonb not null default '{}'::jsonb,
  decisiones jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  constraint aprender_turnos_mes check (mes >= 1 and mes <= 1200 and indice_salud between 0 and 100),
  constraint aprender_turnos_tamano check (pg_column_size(resumen) < 50000 and pg_column_size(decisiones) < 20000),
  constraint aprender_turnos_unico unique (carrera_id, mes)
);
comment on table public.aprender_turnos is 'NODOS · Aprender: resumen de cada mes cerrado y sus decisiones.';
create index if not exists aprender_turnos_usuario_idx on public.aprender_turnos (user_id, created_at desc);
alter table public.aprender_turnos enable row level security;
drop policy if exists "aprender_turnos: dueño lee" on public.aprender_turnos;
create policy "aprender_turnos: dueño lee" on public.aprender_turnos
  for select using ((select auth.uid()) = user_id or public.is_admin());
-- Solo se agrega un turno a una carrera propia; no se edita ni se borra.
drop policy if exists "aprender_turnos: dueño agrega" on public.aprender_turnos;
create policy "aprender_turnos: dueño agrega" on public.aprender_turnos
  for insert with check (
    (select auth.uid()) = user_id
    and exists (select 1 from public.aprender_carreras c where c.id = carrera_id and c.user_id = (select auth.uid()))
  );
revoke all on public.aprender_turnos from anon;
grant select, insert on public.aprender_turnos to authenticated;

-- 3. Lecciones aprendidas (de todas las carreras: base de la herencia) ---------
create table if not exists public.aprender_lecciones (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  leccion_id text not null,
  carrera_id uuid references public.aprender_carreras(id) on delete set null,
  desbloqueada_en timestamptz not null default now(),
  primary key (user_id, leccion_id),
  constraint aprender_lecciones_id check (leccion_id ~ '^[a-z0-9-]{3,60}$')
);
comment on table public.aprender_lecciones is 'NODOS · Aprender: lecciones de NODO desbloqueadas por cada cuenta.';
alter table public.aprender_lecciones enable row level security;
drop policy if exists "aprender_lecciones: dueño lee" on public.aprender_lecciones;
create policy "aprender_lecciones: dueño lee" on public.aprender_lecciones
  for select using ((select auth.uid()) = user_id or public.is_admin());
drop policy if exists "aprender_lecciones: dueño agrega" on public.aprender_lecciones;
create policy "aprender_lecciones: dueño agrega" on public.aprender_lecciones
  for insert with check ((select auth.uid()) = user_id);
revoke all on public.aprender_lecciones from anon;
grant select, insert on public.aprender_lecciones to authenticated;

-- 4. Contenido editable desde el Panel ----------------------------------------
-- Lo incluido vive en el código; una fila con el mismo id lo reemplaza.
-- Solo lo publicado llega a los jugadores.
create table if not exists public.aprender_contenido (
  id text primary key,
  tipo text not null,
  datos jsonb not null,
  estado text not null default 'borrador',
  actualizado_por uuid default auth.uid() references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint aprender_contenido_id check (id ~ '^[a-z0-9-]{3,60}$'),
  constraint aprender_contenido_tipo check (tipo in ('situacion', 'caso')),
  constraint aprender_contenido_estado check (estado in ('borrador', 'revisado', 'publicado')),
  constraint aprender_contenido_tamano check (pg_column_size(datos) < 60000)
);
comment on table public.aprender_contenido is 'NODOS · Aprender: situaciones y casos reales cargados desde el Panel.';
alter table public.aprender_contenido enable row level security;
drop policy if exists "aprender_contenido: leer publicado" on public.aprender_contenido;
create policy "aprender_contenido: leer publicado" on public.aprender_contenido
  for select using (estado = 'publicado' or public.is_admin());
drop policy if exists "aprender_contenido: admin escribe" on public.aprender_contenido;
create policy "aprender_contenido: admin escribe" on public.aprender_contenido
  for insert with check (public.is_admin());
drop policy if exists "aprender_contenido: admin edita" on public.aprender_contenido;
create policy "aprender_contenido: admin edita" on public.aprender_contenido
  for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists "aprender_contenido: admin borra" on public.aprender_contenido;
create policy "aprender_contenido: admin borra" on public.aprender_contenido
  for delete using (public.is_admin());
drop trigger if exists aprender_contenido_touch on public.aprender_contenido;
create trigger aprender_contenido_touch before update on public.aprender_contenido
  for each row execute function public.touch_updated_at();
revoke all on public.aprender_contenido from anon;
grant select, insert, update, delete on public.aprender_contenido to authenticated;

-- 5. Puntos de herencia para la próxima carrera (una por lección distinta) ----
create or replace function public.aprender_puntos_herencia()
returns integer
language sql
stable
security invoker
set search_path = public
as $$
  select count(*)::integer from public.aprender_lecciones where user_id = (select auth.uid());
$$;
revoke all on function public.aprender_puntos_herencia() from public, anon;
grant execute on function public.aprender_puntos_herencia() to authenticated;

notify pgrst, 'reload schema';
